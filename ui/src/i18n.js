let current = 'en';

export function setLanguage(lang) {
  current = LANGUAGES.includes(lang) ? lang : 'en';
  return current;
}

export function getLanguage() {
  return current;
}

/** The text for key in the current language, then English, then the key itself. {name} fills from vars. */
export function t(key, vars = {}) {
  const raw = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

/** An error from the core in the HUD's language when it carries a known code, else its own message. */
export function errorText({ message, code } = {}) {
  return code && STRINGS.en[`error.${code}`] ? t(`error.${code}`) : message;
}

/** Locale for dates and times shown in the HUD. */
export function locale() {
  return current === 'ar' ? 'ar-EG' : 'en-GB';
}

const ATTRIBUTES = [
  ['data-i18n-title', 'title'],
  ['data-i18n-placeholder', 'placeholder'],
  ['data-i18n-aria', 'aria-label'],
  ['data-i18n-alt', 'alt'],
];

/** Sets <html lang dir> and fills every data-i18n element and attribute. Returns the language used. */
export function applyLanguage(lang, doc = globalThis.document) {
  setLanguage(lang);
  doc.documentElement.setAttribute('lang', current);
  doc.documentElement.setAttribute('dir', current === 'ar' ? 'rtl' : 'ltr');
  for (const el of doc.querySelectorAll('[data-i18n]')) el.textContent = t(el.getAttribute('data-i18n'));
  for (const [source, target] of ATTRIBUTES) {
    for (const el of doc.querySelectorAll(`[${source}]`)) el.setAttribute(target, t(el.getAttribute(source)));
  }
  return current;
}

const isDefaultName = (name) => !name || /^haris$/i.test(name);

/** Top-bar brand: the default assistant is "H.A.R.I.S." / "حارس"; a custom name is used as written. */
export function brandFor(name) {
  const n = (name ?? '').trim();
  if (isDefaultName(n)) return t('brand.name');
  return /^[A-Za-z]+$/.test(n) ? `${n.toUpperCase().split('').join('.')}.` : n;
}

/** Name on the assistant's message headers. */
export function speakerFor(name) {
  const n = (name ?? '').trim();
  return (isDefaultName(n) ? t('brand.short') : n).toUpperCase();
}

const ROLE_LABELS = { user: 'who.you', error: 'who.system', notice: 'who.system', reminder: 'who.reminder' };

/** The header of a transcript message: its role's label, or the assistant's name for its replies. */
export function messageHeaderFor(role, assistantName) {
  const key = ROLE_LABELS[role];
  return key ? t(key) : speakerFor(assistantName);
}

/**
 * After a language switch: re-labels the header of every message already in the transcript (the
 * headers carry their role in data-role). The message bodies are left exactly as they are.
 */
export function relabelMessages(root, assistantName) {
  for (const el of root.querySelectorAll('header[data-role]')) {
    el.textContent = messageHeaderFor(el.getAttribute('data-role'), assistantName);
  }
}
